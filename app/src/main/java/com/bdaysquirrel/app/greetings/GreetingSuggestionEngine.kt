package com.bdaysquirrel.app.greetings

enum class GreetingTone(
    val label: String,
) {
    SHORT("Коротко"),
    WARM("Тепло"),
    FUN("С юмором"),
}

data class GreetingContext(
    val birthdayId: Long,
    val name: String,
    val zodiacName: String,
    val ageOnBirthday: Int?,
    val celebrationYear: Int,
)

data class GreetingSuggestion(
    val text: String,
    val tone: GreetingTone,
    val variantIndex: Int,
)

object GreetingSuggestionEngine {
    fun generate(
        context: GreetingContext,
        tone: GreetingTone,
        variantIndex: Int = 0,
    ): GreetingSuggestion {
        require(variantIndex >= 0) { "variantIndex must be non-negative" }

        val name = context.name.trim().ifBlank { "Именинник" }
        val seed = stableSeed(context, tone)
        val zodiacLine = pick(
            values = zodiacLines[context.zodiacName] ?: fallbackZodiacLines,
            seed = seed + 17L,
            variantIndex = variantIndex,
            step = 5L,
        )
        val ageLine = context.ageOnBirthday
            ?.takeIf { it >= 0 && variantIndex % 3 == 0 }
            ?.let { age -> buildAgeLine(age, seed, variantIndex) }

        val text = when (tone) {
            GreetingTone.SHORT -> buildShortGreeting(
                name = name,
                zodiacLine = zodiacLine,
                ageLine = ageLine,
                seed = seed,
                variantIndex = variantIndex,
            )
            GreetingTone.WARM -> buildWarmGreeting(
                name = name,
                zodiacLine = zodiacLine,
                ageLine = ageLine,
                seed = seed,
                variantIndex = variantIndex,
            )
            GreetingTone.FUN -> buildFunGreeting(
                name = name,
                zodiacLine = zodiacLine,
                ageLine = ageLine,
                seed = seed,
                variantIndex = variantIndex,
            )
        }

        return GreetingSuggestion(
            text = text,
            tone = tone,
            variantIndex = variantIndex,
        )
    }

    private fun buildShortGreeting(
        name: String,
        zodiacLine: String,
        ageLine: String?,
        seed: Long,
        variantIndex: Int,
    ): String {
        val opener = pick(shortOpeners, seed + 29L, variantIndex, step = 2L)
            .replace("{name}", name)
        val wish = pick(shortWishes, seed + 41L, variantIndex, step = 3L)
        return listOfNotNull(opener, wish, zodiacLine, ageLine)
            .joinToString(" ")
    }

    private fun buildWarmGreeting(
        name: String,
        zodiacLine: String,
        ageLine: String?,
        seed: Long,
        variantIndex: Int,
    ): String {
        val opener = pick(warmOpeners, seed + 53L, variantIndex, step = 2L)
            .replace("{name}", name)
        val wish = pick(warmWishes, seed + 67L, variantIndex, step = 3L)
        val closing = pick(warmClosings, seed + 79L, variantIndex, step = 2L)
        return listOfNotNull(opener, zodiacLine, wish, ageLine, closing)
            .joinToString(" ")
    }

    private fun buildFunGreeting(
        name: String,
        zodiacLine: String,
        ageLine: String?,
        seed: Long,
        variantIndex: Int,
    ): String {
        val opener = pick(funOpeners, seed + 83L, variantIndex, step = 2L)
            .replace("{name}", name)
        val wish = pick(funWishes, seed + 97L, variantIndex, step = 3L)
        val closing = pick(funClosings, seed + 109L, variantIndex, step = 2L)
        return listOfNotNull(opener, wish, zodiacLine, ageLine, closing)
            .joinToString(" ")
    }

    private fun buildAgeLine(
        age: Int,
        seed: Long,
        variantIndex: Int,
    ): String {
        val years = yearsWord(age)
        val verb = if (years == "год") "принесёт" else "принесут"
        val ending = pick(ageEndings, seed + 127L, variantIndex, step = 2L)
        return "$age $years $verb $ending"
    }

    private fun stableSeed(
        context: GreetingContext,
        tone: GreetingTone,
    ): Long = context.birthdayId * 97L +
        context.celebrationYear.toLong() * 53L +
        context.zodiacName.hashCode().toLong() * 11L +
        tone.ordinal.toLong() * 997L

    private fun pick(
        values: List<String>,
        seed: Long,
        variantIndex: Int,
        step: Long,
    ): String {
        val index = Math.floorMod(
            seed + variantIndex.toLong() * step,
            values.size.toLong(),
        ).toInt()
        return values[index]
    }

    private fun yearsWord(age: Int): String {
        val lastTwo = age % 100
        val last = age % 10
        return when {
            lastTwo in 11..14 -> "лет"
            last == 1 -> "год"
            last in 2..4 -> "года"
            else -> "лет"
        }
    }

